CREATE TABLE IF NOT EXISTS auditoria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id), data TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 entidade VARCHAR(20) NOT NULL CHECK(entidade IN ('ALUNO','MODALIDADE','PLANO','PRODUTO','USUARIO')),
 registro_id BIGINT NOT NULL, acao VARCHAR(20) NOT NULL, detalhes VARCHAR(1000) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_pagamentos_matricula ON pagamentos(matricula_id);
CREATE INDEX IF NOT EXISTS idx_auditoria_registro ON auditoria(entidade, registro_id);
