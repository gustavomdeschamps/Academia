CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(100) NOT NULL, login VARCHAR(60) NOT NULL UNIQUE,
 senha VARCHAR(300) NOT NULL, perfil VARCHAR(20) NOT NULL CHECK(perfil IN ('ADMIN','ATENDENTE')),
 ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS alunos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(100) NOT NULL, cpf VARCHAR(11) NOT NULL UNIQUE,
 telefone VARCHAR(20) NOT NULL, email VARCHAR(120) NOT NULL,
 ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS modalidades (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(80) NOT NULL UNIQUE, descricao VARCHAR(250) NOT NULL
);
CREATE TABLE IF NOT EXISTS planos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(80) NOT NULL UNIQUE, modalidade_id BIGINT NOT NULL REFERENCES modalidades(id),
 valor DECIMAL(10,2) NOT NULL CHECK(valor > 0), meses INT NOT NULL CHECK(meses BETWEEN 1 AND 36)
);
CREATE TABLE IF NOT EXISTS matriculas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 aluno_id BIGINT NOT NULL REFERENCES alunos(id), plano_id BIGINT NOT NULL REFERENCES planos(id),
 inicio DATE NOT NULL, fim DATE NOT NULL CHECK(fim >= inicio),
 valor DECIMAL(10,2) NOT NULL CHECK(valor > 0),
 situacao VARCHAR(20) NOT NULL CHECK(situacao IN ('ATIVA','TRANCADA','CANCELADA')),
 criado_por BIGINT NOT NULL REFERENCES usuarios(id)
);
CREATE TABLE IF NOT EXISTS historico_matriculas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 matricula_id BIGINT NOT NULL REFERENCES matriculas(id), situacao VARCHAR(20) NOT NULL,
 motivo VARCHAR(250) NOT NULL, usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 data TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS pagamentos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 matricula_id BIGINT NOT NULL REFERENCES matriculas(id),
 valor DECIMAL(10,2) NOT NULL CHECK(valor > 0), forma VARCHAR(20) NOT NULL,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id), data TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS produtos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(100) NOT NULL UNIQUE, unidade VARCHAR(20) NOT NULL,
 preco DECIMAL(10,2) NOT NULL CHECK(preco >= 0),
 saldo INT NOT NULL DEFAULT 0 CHECK(saldo >= 0), minimo INT NOT NULL CHECK(minimo >= 0)
);
CREATE TABLE IF NOT EXISTS movimentacoes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 produto_id BIGINT NOT NULL REFERENCES produtos(id),
 tipo VARCHAR(10) NOT NULL CHECK(tipo IN ('ENTRADA','SAIDA')),
 quantidade INT NOT NULL CHECK(quantidade > 0), motivo VARCHAR(250) NOT NULL,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id), data TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_matriculas_aluno ON matriculas(aluno_id);
CREATE INDEX IF NOT EXISTS idx_movimentos_produto ON movimentacoes(produto_id, data);
